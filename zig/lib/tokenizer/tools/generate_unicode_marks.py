"""Generate Unicode 16 mark ranges: SCRIPT UnicodeData.txt OUTPUT."""

import hashlib
import sys
from pathlib import Path

root = next(
    p
    for p in Path(__file__).resolve().parents
    if (p / "scripts/generated_source_licenses.py").is_file()
)
sys.path.insert(0, str(root / "scripts"))
from generated_source_licenses import unicode_source_header

source = Path(sys.argv[1]).read_bytes()
# Exact Unicode 16.0.0 input, matching the existing letter/number table.
EXPECTED = "ff58e5823bd095166564a006e47d111130813dcf8bf234ef79fa51a870edb48f"
if hashlib.sha256(source).hexdigest() != EXPECTED:
    raise SystemExit("expected official Unicode 16.0.0 UnicodeData.txt")
ranges = []
for line in source.decode().splitlines():
    fields = line.split(";")
    if not fields[2].startswith("M"):
        continue
    cp = int(fields[0], 16)
    if ranges and ranges[-1][1] + 1 == cp:
        ranges[-1][1] = cp
    else:
        ranges.append([cp, cp])
body = """// Generated by tools/generate_unicode_marks.py from Unicode 16.0.0.
// Do not edit by hand.
const ranges = [_][2]u21{
"""
body += "".join(f"    .{{ 0x{a:x}, 0x{b:x} }},\n" for a, b in ranges)
body += """};
pub fn isMark(cp: u21) bool {
    var low: usize = 0;
    var high: usize = ranges.len;
    while (low < high) {
        const mid = low + (high - low) / 2;
        if (cp < ranges[mid][0]) high = mid else if (cp > ranges[mid][1]) low = mid + 1 else return true;
    }
    return false;
}
"""
Path(sys.argv[2]).write_text(unicode_source_header(__file__) + body)
